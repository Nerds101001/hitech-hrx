# ---- 8. reliability ------------------------------------------------------
section('8. Reliability rules')
S.append(table([
    hdr(['Rule', 'Specification']),
    ['Idempotency',
     'Every event carries a unique event_id, repeated in the Idempotency-Key '
     'header. Re-delivery is safe: HRX answers 200 with status "duplicate" and '
     'does not write twice.'],
    ['Ordering',
     'Each event carries a monotonic sequence number per call_uid. HRX '
     'tolerates out-of-order arrival and never lets a late call.answered '
     'overwrite a call.completed.'],
    ['Acknowledgement',
     'HRX responds within 2 seconds. It stores the raw payload and processes it '
     'afterwards. 202 means stored, not necessarily processed.'],
    ['Retry',
     'On 5xx or timeout, retry at 1s, 5s, 30s, 2m, 10m, 1h, then hourly up to '
     '24 hours, keeping the SAME event_id. On 4xx other than 429, do not retry '
     '- log it and escalate.'],
    ['Backlog drain',
     'After an outage, send buffered events to /events/batch, up to 500 per '
     'request, processed per item so one bad row never rejects the batch.'],
    ['Time format',
     'ISO-8601 with an explicit offset. Durations are integer seconds.'],
    ['Numbers',
     'E.164 with country code, e.g. +919876543210. If the gateway emits bare '
     '10-digit numbers, normalise before sending.'],
    ['Versioning',
     'Path-versioned at /v1/. Additive changes only within a version; anything '
     'breaking gets /v2 with a 60-day overlap.'],
], [32 * mm, 122 * mm]))

