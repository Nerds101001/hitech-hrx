<?php

namespace App\Services\Telephony;

use Illuminate\Http\Client\PendingRequest;
use Illuminate\Http\Client\Response;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use RuntimeException;

/**
 * Everything HRX sends TO the gateway.
 *
 * Mirrors centrovision-required-v1.yaml. If the vendor's real endpoint names
 * differ, change them here and nothing else in the application moves.
 */
class CentroVisionClient
{
  private function client(): PendingRequest
  {
    $cfg = config('telephony.vendor');

    return Http::baseUrl($cfg['base_url'])
      ->withToken($cfg['api_key'])
      ->acceptJson()
      ->asJson()
      ->timeout($cfg['timeout'])
      ->connectTimeout($cfg['connect_timeout'])
      ->withOptions(['verify' => $cfg['verify_tls']])
      ->retry($cfg['retry_times'], $cfg['retry_sleep_ms'], throw: false);
  }

  /**
   * Click-to-call. The agent's own phone rings first, then the customer.
   *
   * $refId is generated by HRX and must come back on every webhook for this
   * call - it is what ties a click in the UI to the CDR row hours later.
   *
   * @return array{call_uid:string,ref_id:string,status:string}
   */
  public function originate(
    string $refId,
    string $agentId,
    string $destination,
    ?string $campaignId = null,
    ?string $callerId = null,
    ?string $agentNumber = null,
    array $variables = []
  ): array {
    $response = $this->client()->post('/calls/originate', array_filter([
      'ref_id' => $refId,
      'agent_id' => $agentId,
      'agent_number' => $agentNumber,
      'destination' => $destination,
      'campaign_id' => $campaignId,
      'caller_id' => $callerId,
      'record' => true,
      'timeout_seconds' => 45,
      'variables' => $variables ?: null,
    ], fn ($v) => $v !== null));

    return $this->json($response, 'originate');
  }

  public function hangup(string $callUid): array
  {
    return $this->json($this->client()->post("/calls/{$callUid}/hangup"), 'hangup');
  }

  public function hold(string $callUid): array
  {
    return $this->json($this->client()->post("/calls/{$callUid}/hold"), 'hold');
  }

  public function unhold(string $callUid): array
  {
    return $this->json($this->client()->post("/calls/{$callUid}/unhold"), 'unhold');
  }

  public function transfer(string $callUid, string $type, array $target): array
  {
    return $this->json(
      $this->client()->post("/calls/{$callUid}/transfer", array_merge(['type' => $type], $target)),
      'transfer'
    );
  }

  public function conferenceAdd(string $callUid, array $participant): array
  {
    return $this->json($this->client()->post("/calls/{$callUid}/conference", $participant), 'conference');
  }

  public function setAgentState(string $agentId, string $state, ?string $reason = null): array
  {
    return $this->json(
      $this->client()->post("/agents/{$agentId}/state", array_filter([
        'state' => $state,
        'reason' => $reason,
      ])),
      'agent state'
    );
  }

  public function liveAgents(?string $campaignId = null): array
  {
    return $this->json(
      $this->client()->get('/agents/live', array_filter(['campaign_id' => $campaignId])),
      'live agents'
    );
  }

  /**
   * Short-lived signed URL for one recording. HRX streams the bytes itself, so
   * this URL never reaches a browser.
   */
  public function recordingSignedUrl(string $recordingUid): array
  {
    return $this->json(
      $this->client()->get("/recordings/{$recordingUid}/signed-url", [
        'ttl_seconds' => config('telephony.recording.signed_url_ttl'),
      ]),
      'signed url'
    );
  }

  /** One page of CDR for reconciliation. */
  public function cdr(string $from, string $to, ?string $cursor = null): array
  {
    return $this->json(
      $this->client()->get('/cdr', array_filter([
        'from' => $from,
        'to' => $to,
        'cursor' => $cursor,
        'limit' => config('telephony.reconcile.page_size'),
      ])),
      'cdr'
    );
  }

  public function dispositions(): array
  {
    return $this->json($this->client()->get('/dispositions'), 'dispositions');
  }

  private function json(Response $response, string $what): array
  {
    if ($response->failed()) {
      Log::error("[telephony] vendor {$what} call failed", [
        'status' => $response->status(),
        'body' => substr($response->body(), 0, 500),
      ]);

      throw new RuntimeException(
        "CentroVision {$what} failed with HTTP {$response->status()}"
      );
    }

    return (array) $response->json();
  }
}
